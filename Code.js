function expandAdvancePayments() {
  const sheet = SpreadsheetApp.getActiveSpreadsheet().getSheetByName("AdvancePayments");
  const data = sheet.getRange(2, 1, sheet.getLastRow() - 1, 18).getValues(); // A:R

  let results = [];

  data.forEach((row, index) => {
    const houseNo = row[0];                    // A
    const payType = (row[11] || "").toString().trim(); // L
    if (!houseNo) return;

    // ✅ include ล่วงหน้า + ชำระหนี้ค้าง
    if (payType !== "ล่วงหน้า" && payType !== "ชำระหนี้ค้าง") return;

    const months = parseInt(row[16], 10);      // Q No Months
    const totalPayment = parseFloat(row[8]);   // I ยอดชำระ
    const startDate = new Date(row[14]);       // O StartMonth (date)

    if (isNaN(months) || months <= 0 || isNaN(totalPayment) || isNaN(startDate)) {
      Logger.log(`⚠️ Skip row ${index + 2} invalid data`);
      return;
    }

    const monthlyPayment = totalPayment / months;

    for (let i = 0; i < months; i++) {
      const targetDate = new Date(startDate);
      targetDate.setMonth(targetDate.getMonth() + i);
      targetDate.setDate(1);

      const payMonthText = Utilities.formatDate(
        targetDate,
        "Asia/Bangkok",
        "MMMM yy" // เช่น "มกราคม 26"
      );

      results.push([
        row[0], row[1], row[2], row[3], row[4], row[5],
        row[6], row[7],
        parseFloat(monthlyPayment.toFixed(2)),
        row[9], row[10], row[11],
        row[12], row[13],
        targetDate,    // ✅ Column O = Date (ชำระเดือน)
        payMonthText   // ✅ Column P = Text สำหรับแสดงผล
      ]);
    }
  });

  Logger.log("Generated rows: " + results.length);
  return results;
}


