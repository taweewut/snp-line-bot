function DateConvert(date) {
  if (!(date instanceof Date)) {
    date = new Date(date);
  }
  if (isNaN(date)) {
    return "-";
  }

  const yyyy = date.getFullYear().toString();
  const mm = (date.getMonth() + 1).toString().padStart(2, '0');
  const dd = date.getDate().toString().padStart(2, '0');

  return `${dd}-${mm}-${yyyy}`;
}


function replaceVariables(obj, variables) {
  const json = JSON.stringify(obj);
  const replaced = json.replace(/{{(.*?)}}/g, (match, p1) => {
    const value = variables[p1.trim()];
    return (value !== undefined && value !== null && value !== "") ? value.toString() : "-";
  });
  return JSON.parse(replaced);
}


function replaceVariablesInString(str, variables) {
  for (var key in variables) {
    var placeholder = "{{" + key + "}}";
    if (str.includes(placeholder)) {
      str = str.replace(placeholder, variables[key]);
    }
  }
  return str;
}

