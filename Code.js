function doPost(e) {
  try {
    // 🔹 1. Validate incoming request
    if (!e || !e.postData || !e.postData.contents) {
      throw new Error("Missing postData");
    }

    // 🔹 2. Parse LINE webhook payload
    const json = JSON.parse(e.postData.contents);
    const event = json.events && json.events[0];

    if (!event || event.type !== "message" || event.message.type !== "text") {
      Logger.log("📛 Ignored non-text message or missing event");
      return ContentService.createTextOutput("OK");
    }

    // 🔹 3. Log message source for debug (group/user/room)
    Logger.log("📥 Event: " + JSON.stringify(event));
    Logger.log("🔸 Source Type: " + event?.source?.type);

    // 🔹 4. Ignore message from group/room – only allow 1-on-1 user chat
    if (event.source.type !== "user") {
      Logger.log("📛 Ignored non-user message from: " + JSON.stringify(event.source));
      return ContentService.createTextOutput("OK");
    }

    // 🔹 5. Handle user message
    const userText = event.message.text.trim();
    const replyToken = event.replyToken;
    const userId = event.source.userId;
    let replyText = "";

    // 🏠 5a. House number input (1–70)
    if (/^\d+$/.test(userText)) {
      const houseNo = parseInt(userText, 10);
      if (houseNo >= 1 && houseNo <= 70) {
        try {
          replyText = summarizePaymentByHouse(houseNo);
        } catch (err) {
          replyText = `❌ เกิดข้อผิดพลาดขณะดึงข้อมูลบ้านเลขที่ ${houseNo}`;
          Logger.log("❌ summarizePaymentByHouse error: " + err.message);
        }
      } else {
        replyText = `🏠 บ้านเลขที่ไม่ถูกต้อง (กรุณาระบุเลขระหว่าง 1–70)`;
      }

    // 📊 5b. Request report
    } else if (userText === "รายงาน") {
      try {
        sendFlexReportUsingTemplate("C2", userId);  // Send to user only
        replyText = "📊 ส่งรายงานให้คุณเรียบร้อยแล้วครับ";
      } catch (err) {
        replyText = "❌ ไม่สามารถสร้างรายงานได้";
        Logger.log("❌ sendFlexReportUsingTemplate error: " + err.message);
      }

    // ℹ️ 5c. Help message
    } else {
      replyText = `ℹ️ กรุณาพิมพ์เลขบ้าน (1–70) หรือพิมพ์ "รายงาน" เพื่อขอรายงานค่าส่วนกลาง`;
    }

    // 🔹 6. Send reply to user
    replyMessage(replyToken, replyText);

  } catch (error) {
    Logger.log("❌ Error in doPost: " + error.message);
  }

  return ContentService.createTextOutput("OK");
}

// helper function 
function replyMessage(replyToken, replyText) {
  const payload = {
    replyToken: replyToken,
    messages: [
      {
        type: "text",
        text: replyText
      }
    ]
  };

  UrlFetchApp.fetch("https://api.line.me/v2/bot/message/reply", {
    method: "post",
    contentType: "application/json",
    headers: {
      Authorization: "Bearer " + accessToken
    },
    payload: JSON.stringify(payload)
  });
}

